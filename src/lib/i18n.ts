const DICT: Record<UiLang, Record<MsgKey, string>> = { en: EN, zh: ZH };

export type TVars = Record<string, string | number>;
export type TFunc = (key: MsgKey, vars?: TVars) => string;

export function translate(lang: UiLang, key: MsgKey, vars?: TVars): string {
  let text = DICT[lang][key] ?? EN[key] ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.split(`{${name}}`).join(String(value));
    }
  }
  return text;
}

export interface I18nValue {
  lang: UiLang;
  t: TFunc;
}

export const I18nContext = createContext<I18nValue>({
  lang: "en",
  t: (key, vars) => translate("en", key, vars),
});

/** 组件内取当前语言与翻译函数 */
export function useI18n(): I18nValue {
  return useContext(I18nContext);
}
